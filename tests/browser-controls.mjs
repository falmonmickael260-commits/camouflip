async function propPage(options){
  const context=await browser.newContext({...options,...(record?{recordVideo:{dir:'captures',size:options.viewport}}:{})}),page=await context.newPage();
  page.on('pageerror',e=>errors.push(e.message));
  for(let attempt=0;attempt<6;attempt++){
    await page.goto('http://127.0.0.1:5173',{waitUntil:'domcontentloaded',timeout:60000});
    await page.locator('#solo').click({force:true});
    await page.waitForSelector('#lobby:not(.hidden)',{timeout:15000});
    await page.locator('#start').click({force:true});
    await page.waitForSelector('#hud:not(.hidden)',{timeout:15000});
    if(await page.locator('#role').textContent()==='FUGITIF')return {context,page};
  }
  throw new Error('Aucun fugitif obtenu après six salons');
}
